// Regenerate src/data/pokemon/evolutions.ts from Pokemon Showdown data
// (@pkmn/dex, a dev dependency), covering the full National Pokedex (1..1025).
// Run from the repo root:  node scripts/gen-evolutions.mjs
// The output is baked into the repo so runtime never touches the network.
import { Dex } from "@pkmn/dex";
import fs from "fs";
import poke from "../src/data/pokemon/pokemon.json" with { type: "json" };

// pokesprite-style slug (matches our sprite CDN convention).
function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[.'’:]/g, "")
    .replace(/[éÉ]/g, "e")
    .replace(/♀/g, "-f")
    .replace(/♂/g, "-m")
    .replace(/[\s_]+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

// idx -> { name, slug }: prefer our bundled data (proven slugs for 1..905),
// fall back to Showdown for anything else so the full dex is covered.
const map = new Map();
for (const key of Object.keys(poke)) {
  const p = poke[key];
  map.set(Number(p.idx), { name: p.name.eng, slug: p.slug.eng });
}
for (const s of Dex.species.all()) {
  if (s.forme) continue;
  if (typeof s.num !== "number" || s.num < 1 || s.num > 1025) continue;
  if (!map.has(s.num)) map.set(s.num, { name: s.name, slug: slugify(s.name) });
}

function classify(child) {
  const t = child.evoType;
  const level = typeof child.evoLevel === "number" ? child.evoLevel : undefined;
  const item = child.evoItem || undefined;
  const cond = child.evoCondition || undefined;
  if (t === "useItem") return { method: "item", itemName: item, note: cond };
  if (t === "trade") return { method: "trade", itemName: item || "Link Cable", note: cond };
  if (t === "levelFriendship") return { method: "friendship", friendship: 220, note: cond };
  if (!t) return { method: "level", level, note: cond };
  return { method: "special", level: level ?? 30, itemName: item, note: cond || t };
}

const out = {};
let optionCount = 0;
for (const s of Dex.species.all()) {
  if (s.forme) continue;
  if (typeof s.num !== "number" || s.num < 1 || s.num > 1025) continue;
  if (!Array.isArray(s.evos) || !s.evos.length) continue;
  if (!map.has(s.num)) continue;
  const options = [];
  for (const childName of s.evos) {
    const child = Dex.species.get(childName);
    if (!child || child.forme) continue;
    const target = map.get(child.num);
    if (!target) continue;
    const c = classify(child);
    const opt = { toIdx: child.num, toName: target.name, toSlug: target.slug, method: c.method };
    if (c.level !== undefined) opt.level = c.level;
    if (c.itemName) opt.itemName = c.itemName;
    if (c.friendship !== undefined) opt.friendship = c.friendship;
    if (c.note) opt.note = c.note;
    options.push(opt);
  }
  if (options.length) {
    out[s.num] = options;
    optionCount += options.length;
  }
}

const keys = Object.keys(out).map(Number).sort((a, b) => a - b);
const body = keys.map((k) => `  ${k}: ${JSON.stringify(out[k])},`).join("\n");
const file = `// AUTO-GENERATED by scripts/gen-evolutions.mjs. Do not edit by hand.
// Source: Pokemon Showdown data (@pkmn/dex), joined to our national-dex data.
// Covers the full National Pokedex (1..1025). Baked in so runtime needs no network.

export type EvolutionMethod = "level" | "item" | "friendship" | "trade" | "special";

export interface EvolutionOption {
  /** National dex number of the evolved form. */
  toIdx: number;
  /** Evolved form name. */
  toName: string;
  /** Evolved form slug (for sprite lookup). */
  toSlug: string;
  method: EvolutionMethod;
  /** Minimum level required (level and special methods). */
  level?: number;
  /** Item that must be owned and spent (item and trade methods). */
  itemName?: string;
  /** Minimum friendship required (friendship method). */
  friendship?: number;
  /** Human-readable extra condition, shown to the trainer. */
  note?: string;
}

/** Evolutions keyed by the CURRENT form's national dex number. */
export const EVOLUTIONS: Record<number, EvolutionOption[]> = {
${body}
};
`;
fs.writeFileSync(new URL("../src/data/pokemon/evolutions.ts", import.meta.url), file);
console.log("from-species with evolutions:", keys.length, "| options:", optionCount);
console.log("gen9 sample sprigatito(906):", JSON.stringify(out[906]));
console.log("gen9 quaxly(912):", JSON.stringify(out[912]));
