interface ItemRequest {
  itemId: string;
  qty: number;
  note?: string;
}

function readItemRequests(input: unknown): ItemRequest[] {
  if (!Array.isArray(input)) return [];
  return input
    .map((i: any) => ({
      itemId: String(i?.itemId ?? "").slice(0, 100),
      qty: Math.trunc(Number(i?.qty)),
      note: i?.note ? String(i.note).slice(0, 500) : undefined,
    }))
    .filter((i) => i.itemId && Number.isInteger(i.qty) && i.qty > 0 && i.qty <= 999);
}

export const publishForumPost = onCall(async (request) => {
  const uid = requireAuth(request);
  const forum = requireString(request.data?.forum, "forum", 60);
  const threadId = requireString(request.data?.threadId, "threadId", 20);
  const html = requireString(request.data?.html, "post body", 100_000);
  const editPostId = request.data?.editPostId ? String(request.data.editPostId) : undefined;
  const characters = sanitizeCharacters(request.data?.characters);
  const itemRequests = readItemRequests(request.data?.items);
  // Gaia-style signature: attached by default, snapshotted at publish time.
  const attachSignature = request.data?.attachSignature !== false;
  // Battle inputs: try to run away from the wild encounter this post, and
  // which owned pokemon (from the poster's locked team) is doing the fighting.
  const fleeAttempt = request.data?.fleeAttempt === true;
  const fighterIdReq = request.data?.fighterId ? String(request.data.fighterId).slice(0, 80) : "";
  // Optional: evolve one of this post's team pokemon on publish (the composer
  // asks the poster to confirm first). Validated + applied server-side.
  const evolveReq =
    request.data?.evolve && typeof request.data.evolve === "object"
      ? {
          pokemonId: String((request.data.evolve as any).pokemonId ?? "").slice(0, 80),
          toIdx: Math.trunc(Number((request.data.evolve as any).toIdx)) || 0,
        }
      : null;
  const member = await loadMember(uid);
  const curve = evolveReq && evolveReq.pokemonId && evolveReq.toIdx ? await loadLevelingCurve() : [];

  const tRef = threadRef(forum, threadId);
  const pRef = pendingRef(forum, threadId, uid);
  const bagRef = db.doc(`users/${uid}/bag/items`);
  const ownedRef = db.doc(`users/${uid}/bag/owned_pokemons`);
  const teamsRef = db.doc(`users/${uid}/bag/teams`);

  let threadForNotify: FirebaseFirestore.DocumentData | undefined;
  const txResult = await db.runTransaction(async (tx) => {
    // Thread events caused by this post, returned for post-commit notifications.
    let evolvedInfo: EvolveApplied | null = null;
    const shadowedNames: string[] = [];
    // -- reads (all before any write) --------------------------------------
    const [threadSnap, pendingSnap] = await Promise.all([tx.get(tRef), tx.get(pRef)]);
    const thread = assertOpenThread(threadSnap);
    if (!mayPost(thread, member)) {
      throw new HttpsError("permission-denied", "The host limited who can post on this thread.");
    }

    let editSnap: DocumentSnapshot | undefined;
    if (editPostId) {
      editSnap = await tx.get(tRef.collection("posts").doc(editPostId));
      if (!editSnap.exists) throw new HttpsError("not-found", "Post not found.");
      const prev = editSnap.data()!;
      if (prev.ownerUid !== uid) {
        throw new HttpsError("permission-denied", "Only the author can edit a post.");
      }
      if (prev.type && prev.type !== "user") {
        throw new HttpsError("failed-precondition", "System posts cannot be edited.");
      }
    }

    threadForNotify = thread;

    let bag: Record<string, any> = {};
    if (itemRequests.length || evolveReq) {
      const bagSnap = await tx.get(bagRef);
      bag = (bagSnap.data() as Record<string, any>) ?? {};
    }

    // Team pokemon earn progression as people post (see the loop below).
    // Experience is applied immediately and also tallied on the thread
    // (pendingXp) as a running log for the close summary; items and coins stay
    // manual (an admin assigns those at close). The team read is also used by
    // shadow corruption + evolution, so it runs whenever a team is brought.
    const xpConfig = normalizeXpConfig(thread.xpConfig);
    const strippedLength = html.replace(/<[^>]*>/g, "").trim().length;
    const teamIds = characters.map((c: any) => c.teamId).filter(Boolean) as string[];
    // Anti-spam gate: a post must meet the thread's minimum length to progress.
    const xpQualifies = strippedLength >= (xpConfig.minPostLength ?? 0);
    let teamPokemonIds: string[] = [];
    let ownedForXp: Record<string, any> = {};
    if (!editPostId && teamIds.length) {
      const teamsSnap = await tx.get(teamsRef);
      const teams = (teamsSnap.data() as Record<string, { pokemon_ids?: string[] }>) ?? {};
      teamPokemonIds = [
        ...new Set(teamIds.flatMap((teamId) => teams[teamId]?.pokemon_ids ?? [])),
      ];
      if (teamPokemonIds.length || evolveReq) {
        ownedForXp = ((await tx.get(ownedRef)).data() as Record<string, any>) ?? {};
      }
    } else if (evolveReq && !editPostId) {
      ownedForXp = ((await tx.get(ownedRef)).data() as Record<string, any>) ?? {};
    }

    // Team lock: on a normal exp-earning thread a poster is pinned to the
    // team(s) they first posted with, so they cannot rotate teams to farm XP
    // across their whole box. Event/safari/training/no-exp threads are exempt,
    // and a host can open a thread with team changes allowed (set at creation).
    const teamLockable =
      !thread.noXp && !thread.safariContest && !thread.trainingLog && !thread.allowTeamChanges;
    const postTeamIds = [...new Set(teamIds)];
    const lockedTeams = (thread.lockedTeams as Record<string, string[]> | undefined)?.[uid] ?? null;
    let setTeamLock = false;
    if (!editPostId && teamLockable && postTeamIds.length) {
      if (lockedTeams && lockedTeams.length) {
        if (!postTeamIds.every((t) => lockedTeams.includes(t))) {
          throw new HttpsError(
            "failed-precondition",
            "You are locked to the team you first posted with on this thread."
          );
        }
      } else {
        setTeamLock = true; // first post here: remember this team
      }
    }

    // -- compute ------------------------------------------------------------
    const bossActiveForUser =
      !!thread.bossBattle?.active &&
      !((thread.bossBattle.excluded as string[]) ?? []).includes(member.username);

    const itemsUsed = itemRequests.map((req) => {
      const owned = bag[req.itemId];
      if (!owned || (owned.quantity ?? 0) < req.qty) {
        throw new HttpsError(
          "failed-precondition",
          `You do not have ${req.qty}x ${owned?.name ?? "that item"}.`
        );
      }
      const isBall = String(owned.category ?? "").toLowerCase().includes("ball");
      const isFood = isSafariFood(owned.category as string);
      if (isBall && bossActiveForUser) {
        throw new HttpsError("failed-precondition", "Balls cannot be used in a team battle.");
      }
      return {
        itemId: req.itemId,
        name: owned.name as string,
        filePath: (owned.filePath as string) ?? "",
        qty: req.qty,
        isBall,
        isFood,
        ...(req.note ? { note: req.note } : {}),
      };
    });

    const pending = pendingSnap.data() ?? {};
    const encounter = pending.encounter ? { ...pending.encounter } : undefined;
    let encounterCaught = false;
    let encounterForCharacter = "";
    // Slug of a mission foe beaten on this post (bar filled or caught).
    let encounterBeatenSlug = "";
    // Run-away resolution and how hard the enemy hits back this post.
    let encounterFled = false;
    let enemyAttackPct = 0;
    // Safari encounters clear (fled / knocked out) without being caught.
    let safariCleared = false;
    const safariCfg = thread.safariContest;
    if (encounter && safariCfg && encounter.star && !editPostId) {
      // --- Safari Contest turn: fight, feed, or throw a ball ----------------
      const forIds: string[] = Array.isArray(encounter.forCharacterIds)
        ? encounter.forCharacterIds
        : [];
      encounterForCharacter = forIds[0] ?? "";
      const postsToDefeat = Math.max(3, Number(encounter.postsToDefeat) || 3);
      let fightPosts = Number(encounter.fightPosts) || 0;
      let catchBonus = Number(encounter.catchBonus) || 0;
      let failCount = Number(encounter.failCount) || 0;
      const berryBonus = Math.max(0, Number(safariCfg.berryBonus) || 0);
      const berryCap = Math.max(0, Number(safariCfg.berryBonusCap) || 0);
      const runAway = Math.max(0, Math.min(100, Number(safariCfg.runAwayChance) || 0));

      const ball = itemsUsed.find((i) => i.isBall);
      const foodCount = itemsUsed.filter((i) => i.isFood).reduce((n, i) => n + i.qty, 0);
      // Berries/food fed this post nudge the catch rate (they help this throw).
      if (foodCount > 0 && berryBonus > 0) {
        catchBonus = Math.min(berryCap, catchBonus + foodCount * berryBonus);
      }
      const claimCount = ((thread.encounterClaims as Record<string, number>) ?? {})[uid] ?? 0;

      let outcome: string;
      if (ball) {
        const idx = Number(catalogBySlug.get(encounter.slug)?.idx ?? 0);
        const chance = safariCatchChance({
          ballKey: safariBallKey(ball.filePath || "", ball.name || ""),
          fightPosts,
          postsToDefeat,
          berryBonus: catchBonus,
          firstStage: isFirstStageDex(idx),
          failCount,
          firstEncounter: claimCount <= 1,
        });
        encounter.catchChance = chance;
        if (randomInt(100) < chance) {
          encounter.caught = true;
          encounterCaught = true;
          outcome = "caught";
          (ball as any).caughtPokemon = encounter.name;
        } else {
          failCount += 1;
          outcome = "missed";
        }
      } else if (foodCount > 0 && request.data?.safariAction !== "fight") {
        // Feed turn: bonus already applied; the wild Pokemon may still bolt.
        outcome = "fed";
        if (runAway > 0 && randomInt(100) < runAway) {
          outcome = "fled";
          safariCleared = true;
        }
      } else {
        // Fight turn: wear its health down; a knockout ends the encounter.
        fightPosts += 1;
        if (fightPosts >= postsToDefeat) {
          outcome = "ko";
          safariCleared = true;
        } else {
          outcome = "weakened";
        }
        if (!safariCleared && runAway > 0 && randomInt(100) < runAway) {
          outcome = "fled";
          safariCleared = true;
        }
      }
      encounter.fightPosts = fightPosts;
      encounter.catchBonus = catchBonus;
      encounter.failCount = failCount;
      encounter.outcome = outcome;
    } else if (encounter) {
      // Capture progress: a qualifying post weakens the encounter; a ball only
      // catches once progress has reached the required number of posts.
      const required = Number(encounter.required) || 1;
      const forIds: string[] = Array.isArray(encounter.forCharacterIds)
        ? encounter.forCharacterIds
        : [];
      encounterForCharacter = forIds[0] ?? "";
      const postCharIds = characters.map((c: any) => c.id);
      const qualifies = forIds.length === 0 || postCharIds.some((id: string) => forIds.includes(id));
      const enemyStar =
        Number(encounter.star) ||
        starForDex(Number(catalogBySlug.get(String(encounter.slug))?.idx ?? 0));
      let progress = Number(encounter.progress) || 0;
      const wasBeaten = progress >= required;
      const ball = itemsUsed.find((i) => i.isBall);

      if (!editPostId && fleeAttempt && !wasBeaten) {
        // Run-away attempt. Only wild catchable encounters can be fled; bosses
        // and trainer-owned (non-catchable) Pokemon must be fought through.
        if (!encounter.catchable) {
          throw new HttpsError(
            "failed-precondition",
            "You cannot run away from a trainer's Pokemon. Beat it to end the battle."
          );
        }
        const chance = fleeChanceForStar(enemyStar);
        encounter.fleeChance = chance;
        if (randomInt(100) < chance) {
          encounter.outcome = "fled";
          encounterFled = true;
        } else {
          // The escape fails: the turn is spent running, no progress is
          // landed, and the enemy still gets its hit in.
          encounter.outcome = "flee_failed";
          if (qualifies) enemyAttackPct = attackDamageForStar(enemyStar);
        }
      } else if (!editPostId) {
        if (qualifies && progress < required) progress += 1;
        // The enemy hits back on every battle post it survives.
        if (qualifies && progress < required) enemyAttackPct = attackDamageForStar(enemyStar);
      }
      encounter.progress = progress;
      encounter.caught =
        !!ball && !!encounter.catchable && !encounterFled && progress >= required;
      encounterCaught = !!encounter.caught;
      if (encounter.caught && ball) (ball as any).caughtPokemon = encounter.name;
      // A filled bar means the foe is beaten. Record it on mission threads so
      // closing can check the briefing's set foes were all defeated.
      if (!editPostId && thread.missionId && (progress >= required || encounter.caught)) {
        encounterBeatenSlug = String(encounter.slug ?? "");
      }
    }

    // -- damage: the enemy's counter-attack lands on this post's fighter -----
    // Attacking the boss also draws its (heaviest) counter-attack; if both a
    // wild battle and a boss attack happen on one post, only the harder hit
    // lands so a single post never doubles up.
    if (!editPostId && request.data?.attackBoss === true && bossActiveForUser) {
      enemyAttackPct = Math.max(enemyAttackPct, BOSS_ATTACK_DAMAGE);
    }
    let battleBlock: Record<string, unknown> | null = null;
    if (!editPostId && enemyAttackPct > 0 && teamPokemonIds.length) {
      const fighterId =
        fighterIdReq && teamPokemonIds.includes(fighterIdReq) ? fighterIdReq : teamPokemonIds[0];
      const damageMap =
        ((thread.battleDamage as Record<string, Record<string, number>>) ?? {})[uid] ?? {};
      const current = Math.max(0, Math.min(100, Number(damageMap[fighterId]) || 0));
      if (current >= 100) {
        throw new HttpsError(
          "failed-precondition",
          "That pokemon has fainted on this thread. Choose another team pokemon to fight."
        );
      }
      const total = Math.min(100, current + enemyAttackPct);
      const fighterInfo = ownedForXp[fighterId] ?? {};
      battleBlock = {
        fighterId,
        fighterName: String(fighterInfo.species ?? fighterInfo.name ?? "Your pokemon"),
        fighterSlug: String(fighterInfo.image_slug ?? ""),
        damageTaken: enemyAttackPct,
        hpLeft: 100 - total,
        fainted: total >= 100,
      };
    }

    const blocks: Record<string, unknown> = {};
    if (encounter) blocks.encounters = [encounter];
    if (battleBlock) blocks.battle = battleBlock;
    if (itemsUsed.length) {
      blocks.itemsUsed = itemsUsed.map(({ isBall, isFood, ...item }) => item);
    }
    if (pending.dice) blocks.dice = [pending.dice];
    if (pending.random) blocks.randoms = [pending.random];
    if (bossActiveForUser && !editPostId) {
      blocks.boss = { slug: thread.bossBattle.slug, name: thread.bossBattle.name };
    }

    const now = new Date();

    // -- writes ---------------------------------------------------------------
    itemsUsed.forEach((item) => {
      tx.set(
        bagRef,
        { [item.itemId]: { quantity: FieldValue.increment(-item.qty) } },
        { merge: true }
      );
    });

    // The post id must be known before the catch write so the caught pokemon
    // can carry its provenance (which thread/post it was caught in).
    const newPostRef = editPostId ? undefined : tRef.collection("posts").doc();

    if (encounter?.caught) {
      const caughtPostId = editPostId ?? newPostRef!.id;
      // Shiny and gender were rolled when the encounter appeared (and shown in
      // the banner); older pending encounters without them roll here instead.
      tx.set(
        ownedRef,
        {
          [randomUUID()]: buildOwnedPokemon(encounter.slug, now, {
            shiny: typeof encounter.shiny === "boolean" ? encounter.shiny : rollShiny(),
            gender: typeof encounter.gender === "string" ? encounter.gender : undefined,
            characterId: encounterForCharacter || undefined,
            caughtIn: {
              forum,
              threadId,
              postId: caughtPostId,
              threadTitle: (thread.title as string) ?? "",
              ...(safariCfg && encounter.star
                ? { safari: true, star: Number(encounter.star) }
                : {}),
            },
          }),
        },
        { merge: true }
      );
      // Track Safari catches on the thread so the host can judge them at close.
      if (safariCfg && encounter.star) {
        tx.set(
          tRef,
          {
            safariContest: {
              catches: {
                [uid]: FieldValue.arrayUnion({
                  slug: encounter.slug,
                  name: encounter.name,
                  star: Number(encounter.star) || 1,
                  postId: caughtPostId,
                }),
              },
            },
          },
          { merge: true }
        );
      }
    }

    // Progression runs only on normal exp-earning threads (not safari, training
    // or no-exp threads). Experience is admin-configured; friendship, shadow and
    // purification are fixed 0..100 mechanics.
    const earnsStats = !thread.noXp && !thread.safariContest && !thread.trainingLog;
    const qualifies = earnsStats && xpQualifies && !editPostId;
    const maxXp = curve[STAT_MAX] ?? Infinity;
    const expPerPost = xpConfig.experiencePerPost ?? 0;
    // Amounts at least one team pokemon actually earned (for the footer caption;
    // a stat that is maxed out for every team member shows nothing).
    const earned = { experience: 0, friendship: 0, shadow: 0, purification: 0 };

    if (teamPokemonIds.length) {
      const pokeUpdates: Record<string, Record<string, unknown>> = {};
      const xpLog: Record<string, Record<string, unknown>> = {};
      teamPokemonIds.forEach((pokeId) => {
        const poke = ownedForXp[pokeId] ?? {};
        const update: Record<string, unknown> = {};
        const logEntry: Record<string, unknown> = {
          name: poke.species ?? poke.name ?? pokeId,
          slug: poke.image_slug ?? "",
        };
        let logged = false;

        const curExp = Number(poke.experience ?? 0);
        const curFriend = Number(poke.friendship ?? 0);
        const curShadow = Number(poke.shadow ?? 0);
        const curPurif = Number(poke.purification ?? 0);
        const wasShadowed = isShadowedShadow(curShadow);

        // Experience: capped at the level-100 total.
        if (qualifies && expPerPost > 0 && curExp < maxXp) {
          const gain = Math.min(expPerPost, maxXp - curExp);
          update.experience = FieldValue.increment(gain);
          logEntry.experience = FieldValue.increment(gain);
          logged = true;
          earned.experience = expPerPost;
        }
        // Friendship: +2 per post, capped at 100 (a full bar unlocks friendship
        // evolutions).
        if (qualifies && curFriend < STAT_MAX) {
          const next = Math.min(STAT_MAX, curFriend + FRIENDSHIP_PER_POST);
          update.friendship = next;
          logEntry.friendship = FieldValue.increment(next - curFriend);
          logged = true;
          earned.friendship = FRIENDSHIP_PER_POST;
        }

        let newShadow = curShadow;
        let newPurif = curPurif;
        // Purification: only a shadowed pokemon earns it (80% for +5, cap 100).
        if (qualifies && wasShadowed && curPurif < STAT_MAX && randomInt(100) < PURIFICATION_ROLL_PCT) {
          newPurif = Math.min(STAT_MAX, curPurif + PURIFICATION_PER_POST);
          logEntry.purification = FieldValue.increment(newPurif - curPurif);
          logged = true;
          earned.purification = PURIFICATION_PER_POST;
        }
        // Reaching a full purification bar clears the shadow status.
        if (wasShadowed && newPurif >= STAT_MAX) {
          newShadow = 0;
          newPurif = 0;
        }
        // Shadow corruption: a not-yet-shadowed pokemon rolls 25% for +1 (cap
        // 100). Reaching 100 marks it shadowed.
        if (qualifies && !wasShadowed && newShadow < STAT_MAX && randomInt(SHADOW_ROLL) === 0) {
          newShadow = Math.min(STAT_MAX, newShadow + SHADOW_TICK);
          earned.shadow = SHADOW_TICK;
          if (isShadowedShadow(newShadow)) {
            shadowedNames.push(String(poke.species ?? poke.name ?? "A pokemon"));
          }
        }
        if (newShadow !== curShadow) update.shadow = newShadow;
        if (newPurif !== curPurif) update.purification = newPurif;

        if (Object.keys(update).length) pokeUpdates[pokeId] = update;
        if (logged) xpLog[pokeId] = logEntry;
      });
      if (Object.keys(pokeUpdates).length) tx.set(ownedRef, pokeUpdates, { merge: true });
      if (Object.keys(xpLog).length) tx.set(tRef, { pendingXp: { [uid]: xpLog } }, { merge: true });
    }

    // Footer caption amounts: only the stats a team member actually earned.
    const postXpEarned =
      earned.experience || earned.friendship || earned.shadow || earned.purification
        ? {
            ...(earned.experience ? { experience: earned.experience } : {}),
            ...(earned.friendship ? { friendship: earned.friendship } : {}),
            ...(earned.shadow ? { shadow: earned.shadow } : {}),
            ...(earned.purification ? { purification: earned.purification } : {}),
          }
        : null;

    // Evolve a chosen team pokemon on publish (the composer confirmed it). Uses
    // the same server-side rules + item consumption as the evolvePokemon button.
    if (evolveReq && evolveReq.pokemonId && evolveReq.toIdx && !editPostId) {
      evolvedInfo = applyEvolutionInTx(
        tx,
        ownedRef,
        bagRef,
        ownedForXp,
        bag,
        evolveReq.pokemonId,
        evolveReq.toIdx,
        curve
      );
    }

    let resultPostId: string;
    if (editPostId && editSnap) {
      const prev = editSnap.data()!;
      const prevBlocks = prev.blocks ?? {};
      const merged = {
        ...(prevBlocks.boss ? { boss: prevBlocks.boss } : {}),
        encounters: [...(prevBlocks.encounters ?? []), ...((blocks.encounters as any[]) ?? [])],
        itemsUsed: [...(prevBlocks.itemsUsed ?? []), ...((blocks.itemsUsed as any[]) ?? [])],
        dice: [...(prevBlocks.dice ?? []), ...((blocks.dice as any[]) ?? [])],
        randoms: [...(prevBlocks.randoms ?? []), ...((blocks.randoms as any[]) ?? [])],
      };
      tx.update(editSnap.ref, { text: html, blocks: merged, editedAt: now });
      resultPostId = editPostId;
    } else {
      tx.create(newPostRef!, {
        ...authorFields(member),
        character: characters.map((c) => c.name).join(", "),
        characters,
        text: html,
        signature: attachSignature ? member.signature : "",
        timePosted: now,
        type: "user",
        blocks,
        ...(postXpEarned ? { xpEarned: postXpEarned } : {}),
      });

      // Pin the poster to this team for the rest of the thread (anti-farm).
      if (setTeamLock) {
        tx.set(tRef, { lockedTeams: { [uid]: postTeamIds } }, { merge: true });
      }

      // Attacking the boss: opt-in per post, only when a boss is active for
      // this player. Attack posts total across everyone until the boss is down.
      const attackBoss = request.data?.attackBoss === true;
      const bossExtra: Record<string, unknown> = {};
      let bossDefeated = false;
      if (attackBoss && bossActiveForUser) {
        const boss = thread.bossBattle;
        const required = Number(boss.requiredPosts) || Infinity;
        const next = (Number(boss.attackPosts) || 0) + 1;
        bossExtra["bossBattle.attackPosts"] = FieldValue.increment(1);
        if (next >= required) {
          bossExtra["bossBattle.active"] = false;
          bossDefeated = true;
        }
      }
      tx.update(
        tRef,
        activityUpdate(member, now, {
          replyCount: FieldValue.increment(1),
          ...bossExtra,
          // Mission requirement bookkeeping: a beaten (or caught) foe joins the
          // thread's defeated list, checked when the host closes the thread.
          ...(encounterBeatenSlug
            ? { defeatedEncounters: FieldValue.arrayUnion(encounterBeatenSlug) }
            : {}),
          // Damage is per pokemon per thread; 100 = fainted for this thread.
          ...(battleBlock
            ? {
                [`battleDamage.${uid}.${battleBlock.fighterId}`]:
                  100 - Number(battleBlock.hpLeft),
              }
            : {}),
        })
      );
      if (bossDefeated) {
        tx.create(tRef.collection("posts").doc(), {
          ...authorFields(member),
          character: "",
          characters: [],
          text: "",
          timePosted: now,
          type: "boss_end",
          blocks: { boss: { slug: thread.bossBattle.slug, name: thread.bossBattle.name } },
        });
      }
      // Announce an evolution right after the post that triggered it.
      if (evolvedInfo) {
        tx.create(tRef.collection("posts").doc(), {
          ...authorFields(member),
          character: "",
          characters: [],
          text: "",
          timePosted: now,
          type: "evolution",
          blocks: { evolution: { ...evolvedInfo } },
        });
      }
      // Announce any pokemon that just became fully shadowed on this post.
      if (shadowedNames.length) {
        tx.create(tRef.collection("posts").doc(), {
          ...authorFields(member),
          character: "",
          characters: [],
          text: "",
          timePosted: now,
          type: "shadowed",
          blocks: { shadowed: { names: shadowedNames } },
        });
      }
      resultPostId = newPostRef!.id;
    }

    // Consume the per-post rolls. A catchable, uncaught encounter survives
    // (with its new progress) until it is caught, fled, or replaced. A
    // trainer-owned (non-catchable) encounter is a battle too: it survives
    // until beaten, then auto-clears (it can never be caught or fled).
    const trainerBattleOngoing =
      !!encounter &&
      !encounter.catchable &&
      Number(encounter.required) > 0 &&
      (Number(encounter.progress) || 0) < Number(encounter.required);
    if (
      !editPostId &&
      encounter &&
      !encounterCaught &&
      !safariCleared &&
      !encounterFled &&
      (encounter.catchable || trainerBattleOngoing)
    ) {
      tx.set(pRef, { encounter });
    } else if (pendingSnap.exists) {
      tx.delete(pRef);
    }
    return {
      postId: resultPostId,
      snagCaught: encounterCaught,
      evolved: evolvedInfo,
      shadowed: shadowedNames,
    };
  });
  const { postId, snagCaught, evolved: evolvedInfo, shadowed: shadowedNames } = txResult;

  // Post-commit notifications: bookmark watchers + @mentions (Q7).
  if (!editPostId && threadForNotify) {
    const link = `/Forum/${forum}/thread/${threadId}/last`;
    const title = (threadForNotify.title as string) ?? "the thread";
    const watchers = ((threadForNotify.watcherUids as string[]) ?? []).filter((w) => w !== uid);
    await notifyUsers(watchers, {
      type: "bookmark_post",
      text: `${member.username} posted in "${title}"`,
      link,
    });
    const mentioned = await mentionedUids(html, uid).catch(() => [] as string[]);
    await notifyUsers(
      mentioned.filter((m) => !watchers.includes(m)),
      { type: "mention", text: `${member.username} mentioned you in "${title}"`, link }
    );
    // Self notifications so the poster does not miss a thread event they caused.
    if (evolvedInfo) {
      await notifyUsers([uid], {
        type: "evolution",
        text: `Wow! ${evolvedInfo.fromName} evolved into ${evolvedInfo.toName}!`,
        link,
      });
    }
    if (shadowedNames.length) {
      await notifyUsers([uid], {
        type: "shadowed",
        text:
          shadowedNames.length === 1
            ? `${shadowedNames[0]} has become shadowed!`
            : `${shadowedNames.length} of your pokemon have become shadowed!`,
        link,
      });
    }
  }

  // Weekly Snag List checklist (never blocks the publish).
  if (!editPostId) {
    await markSnagTask(uid, "post");
    if (snagCaught) await markSnagTask(uid, "catch");
    if (forum === "Events" || forum === "Quests") await markSnagTask(uid, "activity");
  }

  return { postId };
});

export const publishForumThread = onCall(async (request) => {
  const uid = requireAuth(request);
  const forum = requireString(request.data?.forum, "forum", 60);
  const title = requireString(request.data?.title, "title", 200);
  const html = requireString(request.data?.html, "first post", 100_000);
  const member = await loadMember(uid);

  // Thread-creation permission matrix (mirrors src/Pages/forum/config.ts).
  if (!canCreateInForum(forum, member)) {
    throw new HttpsError("permission-denied", "You cannot create threads here.");
  }
  const pinned = !!request.data?.pinned && isAdmin(member);

  const characters = sanitizeCharacters(request.data?.characters);
  const instructions = String(request.data?.instructions ?? "").slice(0, 2000);
  const tags = (Array.isArray(request.data?.tags) ? request.data.tags : [])
    .slice(0, 15)
    .map((t: unknown) => String(t).slice(0, 40));
  const restricted = !!request.data?.restricted;
  const allowedPosters = (Array.isArray(request.data?.allowedPosters)
    ? request.data.allowedPosters
    : []
  )
    .slice(0, 100)
    .map((n: unknown) => String(n).slice(0, 100));

  let poll: any = null;
  if (request.data?.poll?.question) {
    const options = (Array.isArray(request.data.poll.options) ? request.data.poll.options : [])
      .slice(0, 20)
      .map((o: any) => ({
        id: String(o?.id ?? randomUUID()).slice(0, 50),
        text: String(o?.text ?? "").slice(0, 200),
      }))
      .filter((o: any) => o.text.trim());
    if (options.length >= 2) {
      poll = {
        question: String(request.data.poll.question).slice(0, 300),
        options,
        votes: {},
      };
    }
  }

  let encounterConfig: any = null;
  const rawConfig = request.data?.encounterConfig;
  if (rawConfig?.enabled && rawConfig.listId) {
    encounterConfig = {
      enabled: true,
      disabled: false,
      listId: String(rawConfig.listId).slice(0, 100),
      listName: String(rawConfig.listName ?? "").slice(0, 100),
      mode: rawConfig.mode === "choose" ? "choose" : "roll",
      perUserLimit: Math.min(50, Math.max(1, Math.trunc(Number(rawConfig.perUserLimit)) || 1)),
      nonCatchable: rawConfig.nonCatchable?.listId
        ? {
            listId: String(rawConfig.nonCatchable.listId).slice(0, 100),
            listName: String(rawConfig.nonCatchable.listName ?? "").slice(0, 100),
          }
        : null,
    };
  }

  // XP settings: site defaults from admin/xp_defaults; admins and directors
  // with the AdjustXP capability may override per thread (Q5). Awards cover
  // all four pokemon stats (experience/friendship/purification/shadow).
  const defaultsSnap = await db.doc("admin/xp_defaults").get();
  let xpConfig = normalizeXpConfig(defaultsSnap.data());
  const xpOverride = request.data?.xpConfig;
  if (xpOverride && (isAdmin(member) || hasCap(member, "AdjustXP"))) {
    xpConfig = normalizeXpConfig(xpOverride);
  }

  // Only staff (admins or hosting directors) create roleplays that can award XP
  // instantly; everyone else's threads always defer XP to the close review.
  const staffCreated =
    isAdmin(member) || hasCap(member, "HostMainForum") || hasCap(member, "HostEvents");
  const xpAward = staffCreated && request.data?.xpAward === "instant" ? "instant" : "onClose";

  const threadsCol = db.collection(`forum/${forum}/threads`);
  const countSnap = await threadsCol.count().get();
  const threadId = String(countSnap.data().count + 1);
  const now = new Date();

  const batch = db.batch();
  const tRef = threadsCol.doc(threadId);
  batch.create(tRef, {
    title,
    createdBy: member.username,
    hostUid: uid,
    // Admin-created threads apply XP immediately; non-admin threads accrue XP
    // into pendingXp for review + commit at close (see publishForumPost).
    createdByAdmin: isAdmin(member),
    // staffCreated + xpAward drive the instant-vs-on-close XP choice.
    staffCreated,
    xpAward,
    closed: false,
    private: false,
    pinned,
    tags,
    instructions,
    restricted,
    allowedPosters: restricted ? allowedPosters : [],
    createdAt: now,
    timePosted: now,
    replyCount: 0,
    lastPost: { by: member.username, avatar: member.avatar, at: now },
    participants: { [uid]: { name: member.username, avatar: member.avatar } },
    poll,
    encounterConfig,
    encounterClaims: {},
    bossBattle: null,
    xpConfig,
    // When set, posting here earns no progression (experience/friendship/shadow/
    // purification). An admin can still assign bonuses at close.
    noXp: !!request.data?.noXp,
    // Host choice, set only at creation: members may swap teams between posts
    // (turns off the anti-farm team lock for this thread).
    allowTeamChanges: !!request.data?.allowTeamChanges,
  });
  batch.create(tRef.collection("posts").doc(), {
    ...authorFields(member),
    character: characters.map((c) => c.name).join(", "),
    characters,
    text: html,
    signature: request.data?.attachSignature !== false ? member.signature : "",
    timePosted: now,
    type: "user",
    blocks: {},
  });
  await batch.commit();

  await markSnagTask(uid, "post");
  if (forum === "Events") await markSnagTask(uid, "activity");

  return { threadId };
});

