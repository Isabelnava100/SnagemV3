const SAFARI_BALL_BASE_RATE: Record<string, number> = {
  poke: 50, safari: 50, premier: 50, luxury: 50, net: 50, dusk: 50, nest: 50,
  dive: 50, timer: 50, repeat: 50, fast: 50, heavy: 50, love: 50, friend: 50,
  moon: 50, lure: 50, sport: 50, park: 50, dream: 50, beast: 50, heal: 50,
  quick: 50, level: 50, great: 60, ultra: 70, cherish: 90, master: 100,
};
const SAFARI_MAX_FIGHT_BONUS = 40;
const SAFARI_CATCH_CAP = 95;

function safariBallKey(filePath: string, name: string): string {
  const m = filePath.match(/ball\/([a-z0-9-]+)/i);
  if (m) return m[1].toLowerCase();
  return name.toLowerCase().replace(/\s*ball$/, "").trim();
}
function isSafariFood(category: string): boolean {
  const c = String(category ?? "").toLowerCase();
  return c.includes("berry") || c === "curry-ingredient";
}
function isFirstStageDex(idx: number): boolean {
  return stageForDex(idx) === "stage1";
}
function safariBallBaseRate(
  ballKey: string,
  ctx: { firstStage?: boolean; failCount?: number; firstEncounter?: boolean }
): number {
  let rate = SAFARI_BALL_BASE_RATE[ballKey] ?? 50;
  if (ballKey === "level" && ctx.firstStage) rate = 70;
  if (ballKey === "quick" && ctx.firstEncounter) rate = 80;
  if (ballKey === "heal" && (ctx.failCount ?? 0) > 0) rate = 80;
  return rate;
}
function safariFightBonus(fightPosts: number, postsToDefeat: number): number {
  const span = Math.max(1, postsToDefeat - 1);
  return Math.round((Math.min(fightPosts, span) / span) * SAFARI_MAX_FIGHT_BONUS);
}
function safariCatchChance(p: {
  ballKey: string;
  fightPosts: number;
  postsToDefeat: number;
  berryBonus: number;
  firstStage?: boolean;
  failCount?: number;
  firstEncounter?: boolean;
}): number {
  const base = safariBallBaseRate(p.ballKey, p);
  if (base >= 100) return 100;
  const total =
    base + safariFightBonus(p.fightPosts, p.postsToDefeat) + (p.berryBonus || 0);
  return Math.max(0, Math.min(SAFARI_CATCH_CAP, total));
}

/** Validate + clamp an incoming Safari config (drops unknown/empty pools). */
function sanitizeSafariConfig(raw: any): Record<string, unknown> {
  const tiersIn = Array.isArray(raw?.tiers) ? raw.tiers : [];
  const tiers = tiersIn
    .slice(0, 5)
    .map((t: any) => ({
      star: Math.max(1, Math.min(5, Math.trunc(Number(t?.star)) || 1)),
      rate: Math.max(0, Math.min(100, Math.trunc(Number(t?.rate)) || 0)),
      postsToDefeat: Math.max(3, Math.min(51, Math.trunc(Number(t?.postsToDefeat)) || 3)),
      pokemons: (Array.isArray(t?.pokemons) ? t.pokemons : [])
        .map((s: any) => String(s))
        .filter((s: string) => catalogBySlug.has(s))
        .slice(0, 300),
    }))
    .filter((t: any) => t.pokemons.length);
  if (!tiers.length || !tiers.reduce((s: number, t: any) => s + t.rate, 0)) {
    throw new HttpsError("invalid-argument", "Set an encounter rate and pool for at least one star tier.");
  }
  const prizeIn = Array.isArray(raw?.prizeCoins) ? raw.prizeCoins : [10, 10, 7];
  return {
    name: String(raw?.name ?? "Safari Contest").slice(0, 120),
    blurb: String(raw?.blurb ?? "").slice(0, 2000),
    tiers,
    runAwayChance: Math.max(0, Math.min(100, Math.trunc(Number(raw?.runAwayChance)) || 0)),
    berryBonus: Math.max(0, Math.min(100, Math.trunc(Number(raw?.berryBonus)) || 0)),
    berryBonusCap: Math.max(0, Math.min(100, Math.trunc(Number(raw?.berryBonusCap)) || 0)),
    prizeCoins: [0, 1, 2].map((i) => Math.max(0, Math.trunc(Number(prizeIn[i])) || 0)),
    consolationCoins: Math.max(0, Math.trunc(Number(raw?.consolationCoins)) || 0),
    catches: {},
    results: null,
    finalized: false,
  };
}

export const rollEncounter = onCall(async (request) => {
  const uid = requireAuth(request);
  const forum = requireString(request.data?.forum, "forum", 60);
  const threadId = requireString(request.data?.threadId, "threadId", 20);
  const chosenSlug = request.data?.chosenSlug ? String(request.data.chosenSlug) : undefined;
  const fishing = request.data?.fishing === true;
  // Characters the roller is capturing this encounter for (their own). Empty =
  // personal: any of the roller's posts count toward the capture.
  const forCharacterIds = (Array.isArray(request.data?.forCharacterIds) ? request.data.forCharacterIds : [])
    .slice(0, 6)
    .map((c: unknown) => String(c).slice(0, 60));
  await loadMember(uid);

  // Fishing (the Fishing Pond thread only): any rod from the Snag Mall gets
  // you a weekly cast, and a better rod means better bites. Star odds by
  // best rod owned (1/2/3/4 star): Old 65/30/5/0, Good 60/30/10/0,
  // Super 55/30/10/5 (the Super Rod's 5% reaches the next star level up).
  const ROD_ODDS: Record<number, number[]> = {
    1: [65, 30, 5, 0],
    2: [60, 30, 10, 0],
    3: [55, 30, 10, 5],
  };
  let rodName = "";
  let rodTier = 0;
  if (fishing) {
    const bag = (await db.doc(`users/${uid}/bag/items`).get()).data() ?? {};
    for (const entry of Object.values(bag as Record<string, any>)) {
      if ((Number(entry?.quantity) || 0) <= 0) continue;
      const key = itemKeyOf(entry?.name);
      const tier =
        key === "super-rod" ? 3 : key === "good-rod" ? 2 : key === "old-rod" || key === "fishing-rod" ? 1 : 0;
      if (tier > rodTier) {
        rodTier = tier;
        rodName = String(entry?.name ?? "rod");
      }
    }
    if (!rodTier) {
      throw new HttpsError(
        "failed-precondition",
        "You need a fishing rod. Complete the Rod Thief mission to earn your first, or buy one from the Snag Mall."
      );
    }
  }

  const [listsSnap, starsSnap] = await Promise.all([
    db.doc("admin/pokemon_lists").get(),
    db.doc("admin/star_overrides").get(),
  ]);
  const lists = (listsSnap.data() as Record<string, any>) ?? {};
  // Admin star overrides (set from the Library Pokedex) beat the baked map.
  const starOverrides = (starsSnap.data() ?? {}) as Record<string, unknown>;
  const starFor = (idx: number): number => {
    const o = Math.trunc(Number(starOverrides[String(idx)]));
    return o >= 1 && o <= 7 ? o : starForDex(idx);
  };

  const encounter = await db.runTransaction(async (tx) => {
    const [threadSnap, pendingSnap] = await Promise.all([
      tx.get(threadRef(forum, threadId)),
      tx.get(pendingRef(forum, threadId, uid)),
    ]);
    const thread = assertOpenThread(threadSnap);
    const config = thread.encounterConfig;
    if (!config?.enabled) throw new HttpsError("failed-precondition", "Encounters are not enabled here.");
    if (config.disabled) throw new HttpsError("failed-precondition", "The host turned off encounters.");
    // A pending encounter blocks a new roll, EXCEPT one that is already fully
    // worn down (beaten). Its defeat was recorded when the bar filled, so the
    // player may skip the catch and move on to their next target (mission
    // threads often require several set foes).
    const pendingEnc = pendingSnap.data()?.encounter;
    const pendingBeaten =
      pendingEnc &&
      pendingEnc.postsToDefeat == null &&
      Number(pendingEnc.required) > 0 &&
      Number(pendingEnc.progress ?? 0) >= Number(pendingEnc.required);
    if (pendingEnc && !pendingBeaten) {
      throw new HttpsError(
        "failed-precondition",
        "You already have an encounter waiting for your next post."
      );
    }
    const claims = (thread.encounterClaims as Record<string, number>) ?? {};
    if ((claims[uid] ?? 0) >= (config.perUserLimit ?? 0)) {
      throw new HttpsError("failed-precondition", "You have no encounters left on this thread.");
    }
    // Fresh from the Pokemon Center: a character inside their two-post
    // battle-free window cannot have an encounter rolled FOR them. (Posting
    // itself re-checks the cooldown for whichever characters end up on the
    // post, so an unscoped roll is caught there.)
    const rollerChars = ((((thread.battleLog as Record<string, any>) ?? {})[uid] ?? {}).chars ??
      {}) as Record<string, any>;
    const charCoolingDown = (charId: string) => {
      const l = rollerChars[charId] ?? {};
      const posts = Number(l.posts) || 0;
      const centerAt = Number(l.centerAt) || 0;
      return centerAt > 0 && posts + 1 <= centerAt + 1;
    };
    if (forCharacterIds.some((c: string) => charCoolingDown(c))) {
      throw new HttpsError(
        "failed-precondition",
        "That character is just back from the Pokemon Center. Encounters reopen on their post after next."
      );
    }

    // Safari Contest: weighted star roll, then a uniform pick within that
    // star's pool. Health goes down over fight posts instead of capture posts.
    const safari = thread.safariContest;
    let result: Record<string, unknown>;
    if (safari && Array.isArray(safari.tiers)) {
      const tiers = (safari.tiers as any[]).filter(
        (t) => Number(t?.rate) > 0 && Array.isArray(t?.pokemons) && t.pokemons.length
      );
      if (!tiers.length) throw new HttpsError("failed-precondition", "This contest has no encounters set up.");
      const totalRate = tiers.reduce((s, t) => s + Number(t.rate), 0);
      let r = randomInt(totalRate);
      let tier = tiers[tiers.length - 1];
      for (const t of tiers) {
        if (r < Number(t.rate)) { tier = t; break; }
        r -= Number(t.rate);
      }
      const pool = (tier.pokemons as string[]).filter((s) => catalogBySlug.has(s));
      if (!pool.length) throw new HttpsError("failed-precondition", "This contest tier is empty.");
      const slug = pool[randomInt(pool.length)];
      result = {
        slug,
        name: catalogBySlug.get(slug)?.name ?? slug,
        mode: "roll",
        catchable: true,
        star: Math.max(1, Math.min(5, Number(tier.star) || 1)),
        postsToDefeat: Math.max(3, Number(tier.postsToDefeat) || 3),
        fightPosts: 0,
        catchBonus: 0,
        failCount: 0,
        // Rolled up front so the wild Pokemon's traits show in the banner; the
        // catch write reuses them so what you saw is what you get.
        gender: randomInt(2) === 0 ? "M" : "F",
        shiny: rollShiny(),
        forCharacterIds,
      };
    } else if (fishing) {
      // The Fishing Pond: one cast per member per week (resets Monday 00:00
      // UTC, same as the Snag List). Roll the star first (1/2/3 at 60/30/10),
      // then a uniform pick among that star's Water-types.
      if (!thread.fishingPond) {
        throw new HttpsError("failed-precondition", "Fishing only works at the Fishing Pond thread.");
      }
      const weekId = snagWeekId(new Date());
      const fishClaims = (thread.fishingClaims as Record<string, string>) ?? {};
      if (fishClaims[uid] === weekId) {
        throw new HttpsError(
          "failed-precondition",
          "You already fished this week. The pond restocks Monday 00:00 UTC."
        );
      }
      const odds = ROD_ODDS[rodTier] ?? ROD_ODDS[1];
      let starRollValue = randomInt(100);
      let fishStar = 1;
      for (let s = 0; s < odds.length; s++) {
        if (starRollValue < odds[s]) {
          fishStar = s + 1;
          break;
        }
        starRollValue -= odds[s];
      }
      const waterPool = catalog.filter(
        (c) => typesForDex(Number(c.idx)).includes("Water") && starFor(Number(c.idx)) === fishStar
      );
      if (!waterPool.length) throw new HttpsError("internal", "The waters are empty.");
      const pick = waterPool[randomInt(waterPool.length)];
      result = {
        slug: pick.slug,
        name: pick.name,
        mode: "roll",
        method: "fishing",
        rod: rodName,
        catchable: true,
        star: fishStar,
        required: postsToBeatStar(fishStar),
        progress: 0,
        gender: randomInt(2) === 0 ? "M" : "F",
        shiny: rollShiny(),
        forCharacterIds,
      };
      tx.set(pendingRef(forum, threadId, uid), { encounter: result }, { merge: true });
      tx.update(threadRef(forum, threadId), { [`fishingClaims.${uid}`]: weekId });
      return result;
    } else {
      if (thread.fishingPond) {
        throw new HttpsError(
          "failed-precondition",
          "This is the Fishing Pond: cast your rod instead of rolling an encounter."
        );
      }
      const nonCatchSlugs = new Set(resolveListSlugs(lists, config.nonCatchable?.listId));
      const pool = [...new Set([...resolveListSlugs(lists, config.listId), ...nonCatchSlugs])];
      if (!pool.length) throw new HttpsError("failed-precondition", "The encounter list is empty.");

      let slug: string;
      let mode: "roll" | "choose";
      if (config.mode === "choose") {
        if (!chosenSlug || !pool.includes(chosenSlug)) {
          throw new HttpsError("invalid-argument", "That pokemon is not in the host's list.");
        }
        slug = chosenSlug;
        mode = "choose";
      } else {
        // Star-weighted roll: 4+ star species on a list are rare pulls. The
        // whole rare bucket shares a flat RARE_ENCOUNTER_RATE% chance per roll
        // (uniform within it); everything else splits the rest. A list that is
        // all-rare or all-common keeps the plain uniform roll.
        const rare = new Set(
          pool.filter((s) => starFor(Number(catalogBySlug.get(s)?.idx ?? 0)) >= 4)
        );
        const bucket =
          rare.size && rare.size < pool.length
            ? randomInt(100) < RARE_ENCOUNTER_RATE
              ? [...rare]
              : pool.filter((s) => !rare.has(s))
            : pool;
        slug = bucket[randomInt(bucket.length)];
        mode = "roll";
      }

      const idx = Number(catalogBySlug.get(slug)?.idx ?? 0);
      const star = starFor(idx);
      const required = postsToBeatStar(star);
      result = {
        slug,
        name: catalogBySlug.get(slug)?.name ?? slug,
        mode,
        catchable: !nonCatchSlugs.has(slug) && !thread.bossBattle?.active,
        // Capture progress: the species' star rating (1..7) sets how many
        // qualifying posts it takes to beat it; only then can a ball catch it.
        // `forCharacterIds` restricts which posts count (empty = any of the
        // roller's posts).
        star,
        required,
        progress: 0,
        // Rolled up front so the wild Pokemon's traits show in the banner; the
        // catch write reuses them so what you saw is what you get.
        gender: randomInt(2) === 0 ? "M" : "F",
        shiny: rollShiny(),
        forCharacterIds,
      };
    }
    tx.set(pendingRef(forum, threadId, uid), { encounter: result }, { merge: true });
    tx.update(threadRef(forum, threadId), {
      [`encounterClaims.${uid}`]: FieldValue.increment(1),
    });
    return result;
  });

  return encounter;
});

