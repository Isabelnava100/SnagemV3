function requireString(value: unknown, field: string, max = 200): string {
  if (typeof value !== "string" || !value.trim() || value.length > max) {
    throw new HttpsError("invalid-argument", `Invalid ${field}.`);
  }
  return value;
}

function assertOpenThread(snap: DocumentSnapshot): FirebaseFirestore.DocumentData {
  if (!snap.exists) throw new HttpsError("not-found", "Thread not found.");
  const data = snap.data()!;
  if (data.closed) throw new HttpsError("failed-precondition", "This thread is archived.");
  if (data.paused?.active) {
    throw new HttpsError(
      "failed-precondition",
      "This thread is paused after a team wipe. A staff member decides how it continues."
    );
  }
  return data;
}

// Battle healing: what a medicine item does when used in a battle post.
// Potions heal the post's fighter; revives restore a fainted team pokemon.
// Matched on the item's display name; unmatched medicine has no battle effect.
function healEffectFor(name: string): { heal?: number; revive?: number } | null {
  const n = name.toLowerCase();
  if (n.includes("sacred ash")) return { revive: 100 };
  if (n.includes("max revive")) return { revive: 100 };
  if (n.includes("revive")) return { revive: 50 };
  if (n.includes("full restore") || n.includes("max potion")) return { heal: 100 };
  if (n.includes("hyper potion")) return { heal: 60 };
  if (n.includes("super potion")) return { heal: 40 };
  if (n.includes("potion")) return { heal: 20 };
  // Restorative drinks + treats: modest flat heals so vending-machine and
  // regional items are usable in a battle post, not just potions.
  if (n.includes("lemonade")) return { heal: 60 };
  if (n.includes("moomoo milk")) return { heal: 60 };
  if (n.includes("soda pop")) return { heal: 40 };
  if (n.includes("fresh water")) return { heal: 30 };
  if (n.includes("berry juice") || n.includes("sweet heart")) return { heal: 20 };
  if (/casteliacone|lava cookie|old gateau|shalour sable|lumiose galette|big malasada|rage candy bar|pewter crunchies/.test(n))
    return { heal: 20 };
  return null;
}

function isHost(thread: FirebaseFirestore.DocumentData, member: Member): boolean {
  if (thread.hostUid) return thread.hostUid === member.uid;
  return thread.createdBy === member.username; // legacy threads
}

/** Battle staff (admins + the ManageBattles capability) get host-level access
 * on every thread and are the only ones who may toggle battle mode. */
function isBattleStaff(member: Member): boolean {
  return isAdmin(member) || hasCap(member, "ManageBattles");
}
function hostOrBattleStaff(thread: FirebaseFirestore.DocumentData, member: Member): boolean {
  return isHost(thread, member) || isBattleStaff(member);
}

function mayPost(thread: FirebaseFirestore.DocumentData, member: Member): boolean {
  if (isAdmin(member) || isHost(thread, member)) return true;
  if (!thread.restricted) return true;
  return ((thread.allowedPosters as string[]) ?? []).includes(member.username);
}

function resolveListSlugs(
  lists: Record<string, any> | undefined,
  listId: string | undefined
): string[] {
  const list = listId ? lists?.[listId] : undefined;
  if (!list) return [];
  if (list.rule === "except") {
    const excluded = new Set<string>(list.pokemons ?? []);
    return catalog.filter((p) => !excluded.has(p.slug)).map((p) => p.slug);
  }
  return (list.pokemons as string[]) ?? [];
}

/** Sanitize the client-provided character strips (display data only). */
function sanitizeCharacters(input: unknown): any[] {
  if (!Array.isArray(input)) return [];
  return input.slice(0, 12).map((c: any) => ({
    id: String(c?.id ?? "").slice(0, 100),
    name: String(c?.name ?? "").slice(0, 100),
    imageURL: String(c?.imageURL ?? "").slice(0, 500),
    ...(c?.teamId ? { teamId: String(c.teamId).slice(0, 100) } : {}),
    ...(c?.teamName ? { teamName: String(c.teamName).slice(0, 100) } : {}),
    pokemon: (Array.isArray(c?.pokemon) ? c.pokemon : [])
      .slice(0, 6)
      .filter((p: any) => catalogBySlug.has(p?.slug))
      .map((p: any) => ({
        slug: p.slug as string,
        name: catalogBySlug.get(p.slug)!.name,
      })),
  }));
}

