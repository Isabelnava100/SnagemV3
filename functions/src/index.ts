// --- Buy/sell Gengar Tokens -------------------------------------------------
export const exchangeTokens = onCall(async (request) => {
  const uid = requireAuth(request);
  await loadMember(uid);
  const direction = requireString(request.data?.direction, "direction", 8);
  const amount = requireInt(request.data?.amount ?? 0, "amount", 1, 100000);

  const cfgSnap = await db.doc("admin/casino_config").get();
  const rate = Math.max(1, Math.trunc(Number(cfgSnap.data()?.exchangeRate ?? 2))); // Snag Coins per token

  const currencyRef = db.doc(`users/${uid}/bag/currency`);
  const totals = await db.runTransaction(async (tx) => {
    const cur = (await tx.get(currencyRef)).data() ?? {};
    let poke = parseInt(String(cur.pokecoin ?? "0"), 10) || 0;
    let geng = parseInt(String(cur.gengarcoin ?? "0"), 10) || 0;
    if (direction === "buy") {
      const cost = amount * rate;
      if (poke < cost) throw new HttpsError("failed-precondition", "Not enough Snag Coins.");
      poke -= cost;
      geng += amount;
    } else if (direction === "sell") {
      // House keeps the spread: tokens cash out at 1 Snag Coin each.
      if (geng < amount) throw new HttpsError("failed-precondition", "Not enough Gengar Tokens.");
      geng -= amount;
      poke += amount;
    } else {
      throw new HttpsError("invalid-argument", "Bad direction.");
    }
    tx.set(currencyRef, { pokecoin: poke, gengarcoin: geng }, { merge: true });
    return { pokecoin: poke, gengarcoin: geng };
  });
  return { ok: true, ...totals };
});

// --- Instant games (Hex Roulette, Dream Dice, Payback Pyramid) --------------
export const playCasinoGame = onCall(async (request) => {
  const uid = requireAuth(request);
  await loadMember(uid);
  const game = requireString(request.data?.game, "game", 20);
  const bet = requireInt(request.data?.bet ?? 1, "bet", 1, 5);
  const pick = request.data?.pick;

  const currencyRef = db.doc(`users/${uid}/bag/currency`);
  const result = await db.runTransaction(async (tx) => {
    const cur = (await tx.get(currencyRef)).data() ?? {};
    let geng = parseInt(String(cur.gengarcoin ?? "0"), 10) || 0;
    if (geng < bet) throw new HttpsError("failed-precondition", "Not enough Gengar Tokens.");
    geng -= bet; // stake taken up front

    let win = false;
    let roll: number | number[] = 0;
    let payout = 0;

    if (game === "hexRoulette") {
      const n = requireInt(pick, "pick", 1, 36);
      roll = randomInt(1, 37);
      if (roll === n) { win = true; payout = Math.round(bet * 5.5); }
    } else if (game === "dreamDice") {
      const total = requireInt(pick, "pick", 2, 12);
      const d1 = randomInt(1, 7);
      const d2 = randomInt(1, 7);
      roll = [d1, d2];
      if (d1 + d2 === total) { win = true; payout = bet * (d1 === d2 ? 3 : 2); }
    } else if (game === "paybackPyramid") {
      if (pick !== "even" && pick !== "odd") throw new HttpsError("invalid-argument", "Pick even or odd.");
      roll = randomInt(1, 5); // d4
      const isEven = roll % 2 === 0;
      if ((pick === "even") === isEven) { win = true; payout = bet * 2; }
    } else {
      throw new HttpsError("invalid-argument", "Unknown game.");
    }

    geng += payout; // stake already deducted; add winnings
    tx.set(currencyRef, { gengarcoin: geng }, { merge: true });
    return { win, roll, payout, gengarcoin: geng };
  });
  await markSnagTask(uid, "casino");
  return { ok: true, ...result };
});

// --- Shadow Lotto: buy a ticket --------------------------------------------
// Once entries reach the draw minimum (admin/casino_config.lottoMinTickets,
// default 5), the graders who can run drawLotto get pinged to roll the winner.
const DEFAULT_LOTTO_MIN_TICKETS = 5;

export const buyLottoTicket = onCall(async (request) => {
  const uid = requireAuth(request);
  const member = await loadMember(uid);
  const number = requireInt(request.data?.number ?? 0, "number", 1, 50);

  const currencyRef = db.doc(`users/${uid}/bag/currency`);
  const lottoRef = db.doc("casino/lotto");
  const myRef = db.doc(`users/${uid}/bag/casino`);

  const out = await db.runTransaction(async (tx) => {
    const [curSnap, lottoSnap] = await Promise.all([tx.get(currencyRef), tx.get(lottoRef)]);
    const geng = parseInt(String(curSnap.data()?.gengarcoin ?? "0"), 10) || 0;
    if (geng < 1) throw new HttpsError("failed-precondition", "A ticket costs 1 Gengar Token.");
    const lotto = lottoSnap.data() ?? {};
    const weekId = String(lotto.weekId ?? "current");

    tx.set(currencyRef, { gengarcoin: geng - 1 }, { merge: true });
    tx.set(lottoRef, {
      jackpot: FieldValue.increment(1),
      ticketCount: FieldValue.increment(1),
      weekId,
      tickets: FieldValue.arrayUnion({ uid, name: member.username, number, weekId }),
    }, { merge: true });
    tx.set(myRef, { lottoNumber: number, lottoWeekId: weekId }, { merge: true });
    return {
      number,
      jackpot: (Number(lotto.jackpot ?? 100)) + 1,
      ticketCount: (Number(lotto.ticketCount ?? 0)) + 1,
    };
  });

  // Ping the draw-capable staff exactly once, on the ticket that reaches the
  // minimum (later tickets don't re-notify).
  const cfgSnap = await db.doc("admin/casino_config").get();
  const minTickets = Math.max(
    1,
    Math.trunc(Number(cfgSnap.data()?.lottoMinTickets ?? DEFAULT_LOTTO_MIN_TICKETS))
  );
  if (out.ticketCount === minTickets) {
    const staff = await staffUidsWithCaps(["ReviewRewards"]);
    await notifyUsers(staff, {
      type: "approval",
      text: `Shadow Lotto has ${out.ticketCount} entries and is ready for a draw.`,
      link: "/Casino",
    });
  }

  await markSnagTask(uid, "casino");

  return { ok: true, ...out };
});

// --- Shadow Lotto: draw (grader/admin) -------------------------------------
export const drawLotto = onCall(async (request) => {
  const uid = requireAuth(request);
  const member = await loadMember(uid);
  if (!isGrader(member)) throw new HttpsError("permission-denied", "You cannot draw the lotto.");

  const lottoRef = db.doc("casino/lotto");
  const lottoSnap = await lottoRef.get();
  const lotto = lottoSnap.data() ?? {};
  const drawn = randomInt(1, 51); // 1..50
  const jackpot = Math.max(0, Math.trunc(Number(lotto.jackpot ?? 100)));
  const tickets = (Array.isArray(lotto.tickets) ? lotto.tickets : []) as Array<{ uid: string; number: number }>;
  const winners = [...new Set(tickets.filter((t) => t.number === drawn).map((t) => t.uid))];

  // Split the jackpot evenly among winners. Any floor remainder is handed out
  // one coin at a time to the earliest winners so the whole pot is always paid.
  const share = winners.length ? Math.floor(jackpot / winners.length) : 0;
  const remainder = winners.length ? jackpot - share * winners.length : 0;
  const payoutFor = (index: number) => share + (index < remainder ? 1 : 0);

  const batch = db.batch();
  for (let i = 0; i < winners.length; i++) {
    const cRef = db.doc(`users/${winners[i]}/bag/currency`);
    const cur = (await cRef.get()).data() ?? {};
    batch.set(cRef, { gengarcoin: addCurrency(cur.gengarcoin, payoutFor(i)) }, { merge: true });
  }
  // Reset the pot to the base for the next week.
  const nextWeek = String(Date.now());
  batch.set(lottoRef, { drawNumber: drawn, jackpot: 100, ticketCount: 0, weekId: nextWeek, tickets: [] }, { merge: true });
  await batch.commit();

  // Notify winners of their actual share (top winners get one extra coin from the remainder).
  const topWinners = winners.slice(0, remainder);
  const baseWinners = winners.slice(remainder);
  if (topWinners.length) {
    await notifyUsers(topWinners, { type: "reward", text: `You won the Shadow Lotto! +${share + 1} Gengar Tokens.`, link: "/Casino" });
  }
  if (baseWinners.length) {
    await notifyUsers(baseWinners, { type: "reward", text: `You won the Shadow Lotto! +${share} Gengar Tokens.`, link: "/Casino" });
  }
  return { ok: true, drawn, winners: winners.length, jackpot, share };
});

// ===========================================================================
// The Snag List: weekly activities checklist (/Activities). Six tasks tracked
// server-side by the gameplay callables; finishing all six unlocks one weekly
// Mystery Box. Resets every Monday 00:00 UTC. State: users/{uid}/bag/snaglist
// (server-written only; see firestore.rules).
// ===========================================================================

type SnagTask = "battle" | "casino" | "post" | "catch" | "activity" | "mall";
const SNAG_TASKS: SnagTask[] = ["battle", "casino", "post", "catch", "activity", "mall"];

/** Monday-anchored UTC week id: the date of this week's Monday, "YYYY-MM-DD". */
function snagWeekId(now: Date): string {
  const d = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  const sinceMonday = (d.getUTCDay() + 6) % 7;
  d.setUTCDate(d.getUTCDate() - sinceMonday);
  return d.toISOString().slice(0, 10);
}

/**
 * Mark one Snag List task done for the current week. Called by the gameplay
 * callables after their main action commits; never throws, so checklist
 * bookkeeping can never break gameplay. Week rollover resets the checklist;
 * completing all six stamps the week and advances the streak (consecutive
 * completed weeks).
 */
async function markSnagTask(uid: string, task: SnagTask): Promise<void> {
  try {
    const ref = db.doc(`users/${uid}/bag/snaglist`);
    await db.runTransaction(async (tx) => {
      const snap = await tx.get(ref);
      const data = snap.data() ?? {};
      const now = new Date();
      const weekId = snagWeekId(now);
      const sameWeek = data.weekId === weekId;
      const tasks: Record<string, boolean> = sameWeek ? { ...(data.tasks ?? {}) } : {};
      if (tasks[task]) return;
      tasks[task] = true;

      const updates: Record<string, unknown> = {
        weekId,
        tasks,
        ...(sameWeek ? {} : { boxClaimed: false, boxChoice: null }),
      };
      const allDone = SNAG_TASKS.every((t) => tasks[t]);
      if (allDone && data.completedWeekId !== weekId) {
        const prevWeek = snagWeekId(new Date(now.getTime() - 7 * 86_400_000));
        updates.completedWeekId = weekId;
        updates.streak = data.completedWeekId === prevWeek ? Number(data.streak ?? 0) + 1 : 1;
      }
      tx.set(ref, updates, { merge: true });
    });
  } catch {
    // Checklist bookkeeping must never block the action that triggered it.
  }
}

// Mystery Egg pool: baby pokemon only, hatched straight into the bag.
const SNAG_EGG_POOL = [
  "pichu", "cleffa", "igglybuff", "togepi", "azurill", "happiny", "munchlax",
  "riolu", "elekid", "magby", "smoochum", "tyrogue", "bonsly", "mime-jr",
  "wynaut", "budew", "chingling", "mantyke",
];

/** Open the weekly Mystery Box: all six tasks required, one box per week. */
export const claimSnagBox = onCall(async (request) => {
  const uid = requireAuth(request);
  await loadMember(uid);
  const choice = String(request.data?.choice ?? "");
  if (!["random", "currency", "egg"].includes(choice)) {
    throw new HttpsError("invalid-argument", "Pick a box first.");
  }

  // Pre-pick the random-item reward outside the transaction (reads the shop
  // catalog); the transaction only validates state and applies the grant.
  let randomItem: { itemId: string; name: string; filePath: string; category: string } | null =
    null;
  if (choice === "random") {
    const shopSnap = await db.doc("shops/golden-sarcophagus").get();
    const sections = (shopSnap.data()?.sections ?? []) as Array<{
      items?: Array<{ itemId: string; name?: string; filePath?: string; category?: string }>;
    }>;
    const pool = sections.flatMap((s) => s.items ?? []);
    if (!pool.length) throw new HttpsError("failed-precondition", "The item pool is empty.");
    const picked = pool[randomInt(pool.length)];
    randomItem = {
      itemId: picked.itemId,
      name: picked.name ?? picked.itemId,
      filePath: picked.filePath ?? "",
      category: picked.category ?? "other-item",
    };
  }
  const eggSlug = SNAG_EGG_POOL[randomInt(SNAG_EGG_POOL.length)];

  const ref = db.doc(`users/${uid}/bag/snaglist`);
  const currencyRef = db.doc(`users/${uid}/bag/currency`);
  const bagRef = db.doc(`users/${uid}/bag/items`);
  const pokeRef = db.doc(`users/${uid}/bag/owned_pokemons`);
  const weekId = snagWeekId(new Date());

  const reward = await db.runTransaction(async (tx) => {
    const [snap, curSnap] = await Promise.all([tx.get(ref), tx.get(currencyRef)]);
    const data = snap.data() ?? {};
    if (data.weekId !== weekId) {
      throw new HttpsError("failed-precondition", "The list reset for a new week. Finish the new one first.");
    }
    const tasks = (data.tasks ?? {}) as Record<string, boolean>;
    if (!SNAG_TASKS.every((t) => tasks[t])) {
      throw new HttpsError("failed-precondition", "Finish all six tasks first.");
    }
    if (data.boxClaimed) {
      throw new HttpsError("failed-precondition", "You already opened this week's box.");
    }

    let text: string;
    if (choice === "currency") {
      const cur = curSnap.data() ?? {};
      tx.set(
        currencyRef,
        {
          pokecoin: addCurrency(cur.pokecoin, 8),
          gengarcoin: addCurrency(cur.gengarcoin, 4),
        },
        { merge: true }
      );
      text = "8 Snag Coins and 4 Gengar Tokens";
    } else if (choice === "egg") {
      const now = new Date();
      tx.set(
        pokeRef,
        { [randomUUID()]: buildOwnedPokemon(eggSlug, now, {}) },
        { merge: true }
      );
      const hatched = catalogBySlug.get(eggSlug)?.name ?? eggSlug;
      text = `a Mystery Egg that hatched into ${hatched}`;
    } else {
      bagIncrement(tx, bagRef, randomItem!.itemId, randomItem!, 1);
      text = `1x ${randomItem!.name}`;
    }

    tx.set(ref, { boxClaimed: true, boxChoice: choice }, { merge: true });
    return text;
  });

  await notifyUsers([uid], {
    type: "reward",
    text: `Weekly Mystery Box opened: ${reward}.`,
    link: "/Activities",
  });
  return { ok: true, reward };
});
